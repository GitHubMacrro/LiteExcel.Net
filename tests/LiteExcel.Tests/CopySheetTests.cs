    [Fact]
    public void Copy_CellValuesStylesFormulasHyperlinksCopied()
    {
        var wb = Excel.Create();
        var ws = wb.Worksheets["Sheet1"];
        ws.SetValue("A1", "文本");
        ws.SetValue("B1", 42.5);
        ws.SetValue("C1", true);
        ws.SetValue("D1", new DateTime(2024, 3, 15));
        ws.SetValue("A2", 0);
        ws.Cell("A2").Formula = "SUM(B1:B1)";
        ws.Cell("A2").IsFormula = true;
        ws.Cell("A1").Style = new CellStyle { Bold = true, FontColor = "#FF0000" };
        ws.Cell("A1").NumberFormat = "General";
        ws.Cell("B1").Hyperlink = new Hyperlink { Target = "https://example.com", Tooltip = "提示" };
        ws.SetValue("E5", "末尾");

        var copy = wb.Worksheets.Copy("Sheet1");

        Assert.Equal("文本", copy.Cell("A1").GetString());
        Assert.Equal(42.5, copy.Cell("B1").GetDouble());
        Assert.True(copy.Cell("C1").GetBoolean());
        Assert.Equal(new DateTime(2024, 3, 15), copy.Cell("D1").GetDateTime());
        Assert.Equal("SUM(B1:B1)", copy.Cell("A2").Formula);
        Assert.True(copy.Cell("A2").IsFormula);
        Assert.True(copy.Cell("A1").Style!.Bold);
        Assert.Equal("#FF0000", copy.Cell("A1").Style!.FontColor);
        Assert.Equal("https://example.com", copy.Cell("B1").Hyperlink!.Target);
        Assert.Equal("提示", copy.Cell("B1").Hyperlink!.Tooltip);
        Assert.Equal("末尾", copy.Cell("E5").GetString());
        Assert.Equal(5, copy.RowCount);
    }

    [Fact]
    public void Copy_ModifyingCopyDoesNotAffectSource()
    {
        var wb = Excel.Create();
        var ws = wb.Worksheets["Sheet1"];
        ws.SetValue("A1", "原值");
        ws.Cell("A1").Style = new CellStyle { Bold = true, FontColor = "#112233" };
        ws.Cell("B1").Hyperlink = new Hyperlink { Target = "https://a.example" };
        ws.SetValue("A2", 1);
        ws.Cell("A2").Formula = "1+1";
        ws.Cell("A2").IsFormula = true;

        var copy = wb.Worksheets.Copy("Sheet1");

        // 改副本的值、样式、超链接、公式
        copy.Cell("A1").SetValue("改过");
        copy.Cell("A1").Style!.Bold = false;
        copy.Cell("A1").Style!.FontColor = "#000000";
        copy.Cell("B1").Hyperlink!.Target = "https://b.example";
        copy.Cell("A2").Formula = "2+2";

        Assert.Equal("原值", ws.Cell("A1").GetString());
        Assert.True(ws.Cell("A1").Style!.Bold);
        Assert.Equal("#112233", ws.Cell("A1").Style!.FontColor);
        Assert.Equal("https://a.example", ws.Cell("B1").Hyperlink!.Target);
        Assert.Equal("1+1", ws.Cell("A2").Formula);
    }

    [Fact]
    public void Copy_StructurePropertiesCopied()
    {
        var wb = Excel.Create();
        var ws = wb.Worksheets["Sheet1"];
        ws.SetValue("A1", "标题");
        ws.SetValue("A2", 10);
        ws.SetValue("A3", 20);
        ws.FreezeRows = 1;
        ws.FreezeColumns = 2;
        ws.ColumnWidths = new Dictionary<int, double> { [0] = 20.5, [2] = 8 };
        ws.RowHeights = new Dictionary<int, double> { [0] = 30, [4] = 12 };
        ws.Merge("A1:C1");
        ws.Comments = new Dictionary<string, string> { ["A2"] = "批注内容" };
        ws.RowStyles = new Dictionary<int, CellStyle> { [0] = new CellStyle { Bold = true } };
        ws.ColumnStyles = new Dictionary<int, CellStyle> { [1] = new CellStyle { Italic = true } };
        ws.HeaderStyle = new CellStyle { Bold = true, FontColor = "#00FF00" };
        ws.Validations = new List<DataValidation>
        {
            new() { Sqref = "A2:A3", Type = DataValidationType.WholeNumber, Formula1 = "1", Formula2 = "100", AllowBlank = true },
        };
        ws.Filter = new AutoFilter
        {
            Range = "A1:A3",
            Columns = { new FilterColumn { ColumnIndex = 0, Type = FilterType.Compare, Operator = FilterOperator.GreaterThan, MinValue = "5" } },
        };

        var copy = wb.Worksheets.Copy("Sheet1");

        Assert.Equal(1, copy.FreezeRows);
        Assert.Equal(2, copy.FreezeColumns);
        Assert.Equal(20.5, copy.ColumnWidths![0]);
        Assert.Equal(8, copy.ColumnWidths![2]);
        Assert.Equal(30, copy.RowHeights![0]);
        Assert.Equal(12, copy.RowHeights![4]);
        Assert.Single(copy.MergedRanges);
        Assert.Equal(ws.MergedRanges[0].FirstCol, copy.MergedRanges[0].FirstCol);
        Assert.Equal("批注内容", copy.Comments!["A2"]);
        Assert.NotNull(copy.RowStyles);
        Assert.NotNull(copy.ColumnStyles);
        Assert.NotNull(copy.HeaderStyle);
        Assert.Single(copy.Validations!);
        Assert.Equal("1", copy.Validations![0].Formula1);
        Assert.NotNull(copy.Filter);
        Assert.Equal("A1:A3", copy.Filter!.Range);
        Assert.Single(copy.Filter.Columns);
        Assert.Equal(FilterOperator.GreaterThan, copy.Filter.Columns[0].Operator);

        // 深拷贝验证：改副本的集合元素不影响源
        copy.ColumnWidths![0] = 99;
        copy.RowStyles![0].Bold = false;
        copy.Validations![0].Formula1 = "999";
        copy.Filter.Columns[0].MinValue = "77";
        copy.Comments!["A2"] = "改过";

        Assert.Equal(20.5, ws.ColumnWidths![0]);
        Assert.True(ws.RowStyles![0].Bold);
        Assert.Equal("1", ws.Validations![0].Formula1);
        Assert.Equal("5", ws.Filter!.Columns[0].MinValue);
        Assert.Equal("批注内容", ws.Comments!["A2"]);
    }

    [Fact]
    public void Copy_ConditionalFormats_DeepCopied()
    {
        var wb = Excel.Create();
        var ws = wb.Worksheets["Sheet1"];
        ws.SetValue("A1", 1);
        ws.ConditionalFormats.Add(new ConditionalFormat
        {
            Sqref = "A1:A10",
            Type = ConditionalFormatType.CellIs,
            Operator = ConditionalOperator.GreaterThan,
            Formula = "50",
            Style = new CellStyle { Bold = true, FontColor = "#FF0000" },
        });
        ws.ConditionalFormats.Add(new ConditionalFormat
        {
            Sqref = "B1:B10",
            Type = ConditionalFormatType.IconSet,
            IconSet = new IconSetInfo { Style = IconSetStyle.ThreeArrows, Thresholds = new[] { 33.0, 67.0 } },
        });
        ws.ConditionalFormats.Add(new ConditionalFormat
        {
            Sqref = "C1:C10",
            Type = ConditionalFormatType.ColorScale,
            ColorScale = new ColorScaleInfo { LowColor = "111111", HighColor = "222222", MidColor = "333333" },
        });

        var copy = wb.Worksheets.Copy("Sheet1");

        Assert.Equal(3, copy.ConditionalFormats.Count);
        Assert.Equal("A1:A10", copy.ConditionalFormats[0].Sqref);
        Assert.True(copy.ConditionalFormats[0].Style!.Bold);
        Assert.Equal(new[] { 33.0, 67.0 }, copy.ConditionalFormats[1].IconSet!.Thresholds);
        Assert.Equal("333333", copy.ConditionalFormats[2].ColorScale!.MidColor);

        // 深拷贝：改副本的 style / 阈值 / 颜色不影响源
        copy.ConditionalFormats[0].Style!.Bold = false;
        copy.ConditionalFormats[1].IconSet!.Thresholds![0] = 1;
        copy.ConditionalFormats[2].ColorScale!.MidColor = "FFFFFF";

        Assert.True(ws.ConditionalFormats[0].Style!.Bold);
        Assert.Equal(33.0, ws.ConditionalFormats[1].IconSet!.Thresholds![0]);
        Assert.Equal("333333", ws.ConditionalFormats[2].ColorScale!.MidColor);
    }

