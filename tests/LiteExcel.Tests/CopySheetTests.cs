    [Fact]
    public void Copy_TablesRenamedAndUnique()
    {
        var wb = Excel.Create();
        var ws = wb.Worksheets["Sheet1"];
        ws.SetValue("A1", "Col1");
        ws.SetValue("B1", "Col2");
        ws.SetValue("A2", 1);
        ws.SetValue("B2", 2);
        ws.AddTable("A1:B2", "DataTable");

        var copy = wb.Worksheets.Copy("Sheet1");

        Assert.Single(copy.Tables);
        // 表名全簿唯一
        Assert.NotEqual("DataTable", copy.Tables[0].Name);
        var allNames = wb.Worksheets.SelectMany(s => s.Tables).Select(t => t.Name).ToList();
        Assert.Equal(allNames.Count, allNames.Distinct(StringComparer.OrdinalIgnoreCase).Count());
    }

    [Fact]
    public void Copy_SaveAndReopen_BothSheetsIntact()
    {
        var file = GetTempFile();
        try
        {
            var wb = Excel.Create();
            var ws = wb.Worksheets["Sheet1"];
            ws.SetValue("A1", "表头");
            ws.SetValue("A2", 123);
            ws.Merge("C1:D1");
            ws.FreezeRows = 1;

            wb.Worksheets.Copy("Sheet1");
            wb.SaveAs(file);

            var opened = Excel.Open(file);
            Assert.Equal(2, opened.Worksheets.Count);
            Assert.Equal("Sheet1", opened.Worksheets[0].Name);
            Assert.Equal("Sheet1 (2)", opened.Worksheets[1].Name);
            foreach (var s in opened.Worksheets)
            {
                Assert.Equal("表头", s.Cell("A1").GetString());
                Assert.Equal(123.0, s.Cell("A2").GetDouble());
                Assert.Single(s.MergedRanges);
                Assert.Equal(1, s.FreezeRows);
            }
        }
        finally { if (File.Exists(file)) File.Delete(file); }
    }

    [Theory]
    [InlineData(ExcelFormat.Xlsx, ".xlsx")]
    [InlineData(ExcelFormat.Xlsb, ".xlsb")]
    [InlineData(ExcelFormat.Xls, ".xls")]
    public void Copy_RoundTrip_MultiFormat(ExcelFormat format, string ext)
    {
        var file = GetTempFile(ext);
        try
        {
            var wb = Excel.Create(format: format);
            var ws = wb.Worksheets["Sheet1"];
            ws.SetValue("A1", "多格式");
            ws.SetValue("B2", 9.5);

            wb.Worksheets.Copy("Sheet1");
            wb.SaveAs(file, format);

            var opened = Excel.Open(file, format);
            Assert.Equal(2, opened.Worksheets.Count);
            Assert.Equal("多格式", opened.Worksheets[1].Cell("A1").GetString());
            Assert.Equal(9.5, opened.Worksheets[1].Cell("B2").GetDouble());
            // 原件未受影响
            Assert.Equal("多格式", opened.Worksheets[0].Cell("A1").GetString());
        }
        finally { if (File.Exists(file)) File.Delete(file); }
    }

